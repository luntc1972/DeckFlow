using DeckFlow.Core.Knowledge;
using DeckFlow.Core.Storage;
using Npgsql;
using Xunit;

namespace DeckFlow.Web.Tests.Integration;

public sealed class PerDeckSchemaCompactionPostgresTests : IClassFixture<PostgresContainerFixture>
{
    private readonly PostgresContainerFixture _fixture;

    public PerDeckSchemaCompactionPostgresTests(PostgresContainerFixture fixture) => _fixture = fixture;

    [PostgresFact]
    public async Task EnsureSchema_LegacyPostgresPerDeckTables_DropsIdAndPromotesGrain()
    {
        await using var database = await CreateDatabaseAsync(await _fixture.GetConnectionStringOrSkipAsync());
        await CreateLegacyTablesAsync(database.ConnectionString);
        await EnsureAsync(database.ConnectionString);
        var repository = Repository(database.ConnectionString);
        await repository.PersistObservedCategoriesAsync("legacy:deck-1", "Sol Ring", new[] { "Ramp" }, quantity: 1, board: "mainboard", deckCountIncrement: 1);
        await repository.PersistCardDeckTotalsAsync("legacy:deck-1", "Sol Ring", board: "mainboard", deckCountIncrement: 1);

        await AssertCompactedAsync(database.ConnectionString);
        Assert.Equal(1L, await ScalarAsync(database.ConnectionString, "SELECT COUNT(1) FROM card_category_observations;"));
        Assert.Equal(1L, await ScalarAsync(database.ConnectionString, "SELECT COUNT(1) FROM card_deck_totals;"));

        var secondConnectionString = new NpgsqlConnectionStringBuilder(database.ConnectionString)
        {
            ApplicationName = $"df-compact-{Guid.NewGuid():N}",
        }.ConnectionString;
        await EnsureAsync(secondConnectionString);
        await AssertCompactedAsync(secondConnectionString);
    }

    [PostgresFact]
    public async Task EnsureSchema_FreshPostgres_CreatesGrainPrimaryKeyWithoutId()
    {
        await using var database = await CreateDatabaseAsync(await _fixture.GetConnectionStringOrSkipAsync());
        await EnsureAsync(database.ConnectionString);
        await AssertCompactedAsync(database.ConnectionString);

        var secondConnectionString = new NpgsqlConnectionStringBuilder(database.ConnectionString)
        {
            ApplicationName = $"df-compact-{Guid.NewGuid():N}",
        }.ConnectionString;
        await EnsureAsync(secondConnectionString);
        await AssertCompactedAsync(secondConnectionString);
    }

    [PostgresFact]
    public async Task EnsureSchema_LegacyTableLocked_SkipsCompactionWithoutFailing()
    {
        await using var database = await CreateDatabaseAsync(await _fixture.GetConnectionStringOrSkipAsync());
        await CreateLegacyTablesAsync(database.ConnectionString);
        await using var holder = new NpgsqlConnection(database.ConnectionString);
        await holder.OpenAsync();
        await using var transaction = await holder.BeginTransactionAsync();
        await using (var lockCommand = new NpgsqlCommand("LOCK TABLE card_category_observations IN ACCESS SHARE MODE;", holder, transaction))
        {
            await lockCommand.ExecuteNonQueryAsync();
        }

        await EnsureAsync(database.ConnectionString);
        Assert.Equal(1L, await ScalarAsync(database.ConnectionString, "SELECT COUNT(1) FROM information_schema.columns WHERE table_name = 'card_category_observations' AND column_name = 'id';"));
        Assert.Equal(0L, await ScalarAsync(database.ConnectionString, "SELECT COUNT(1) FROM information_schema.columns WHERE table_name = 'card_deck_totals' AND column_name = 'id';"));

        await transaction.CommitAsync();
        await EnsureAsync(new NpgsqlConnectionStringBuilder(database.ConnectionString) { ApplicationName = $"df-compact-{Guid.NewGuid():N}" }.ConnectionString);
        await AssertCompactedAsync(database.ConnectionString);
    }

    private static async Task EnsureAsync(string connectionString) =>
        await Repository(connectionString).EnsureSchemaAsync();

    private static CategoryKnowledgeRepository Repository(string connectionString) =>
        new(new RelationalDatabaseConnection(RelationalDatabaseProvider.Postgres, connectionString));

    private static async Task CreateLegacyTablesAsync(string connectionString)
    {
        const string sql = """
            CREATE TABLE card_category_observations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id BIGINT NOT NULL, card_id BIGINT NOT NULL, card_name TEXT NOT NULL, category TEXT NOT NULL, board TEXT NOT NULL DEFAULT 'mainboard', deck_count INTEGER NOT NULL DEFAULT 0, count INTEGER NOT NULL, last_seen_utc TEXT NOT NULL);
            CREATE TABLE card_deck_totals (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_id BIGINT NOT NULL, card_id BIGINT NOT NULL, board TEXT NOT NULL DEFAULT 'mainboard', deck_count INTEGER NOT NULL DEFAULT 0, last_seen_utc TEXT NOT NULL);
            CREATE UNIQUE INDEX ux_obs_grain ON card_category_observations (source_id, card_id, category, board);
            CREATE UNIQUE INDEX ux_totals_grain ON card_deck_totals (source_id, card_id, board);
            INSERT INTO card_category_observations (source_id, card_id, card_name, category, board, deck_count, count, last_seen_utc) VALUES (1, 1, 'Sol Ring', 'Ramp', 'mainboard', 1, 1, '2026-01-01T00:00:00.0000000Z');
            INSERT INTO card_deck_totals (source_id, card_id, board, deck_count, last_seen_utc) VALUES (1, 1, 'mainboard', 1, '2026-01-01T00:00:00.0000000Z');
            """;
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    private static async Task AssertCompactedAsync(string connectionString)
    {
        Assert.Equal(0L, await ScalarAsync(connectionString, "SELECT COUNT(1) FROM information_schema.columns WHERE table_name IN ('card_category_observations', 'card_deck_totals') AND column_name = 'id';"));
        Assert.Equal(1L, await ScalarAsync(connectionString, "SELECT COUNT(1) FROM pg_constraint WHERE conname = 'ux_obs_grain' AND pg_get_constraintdef(oid) = 'PRIMARY KEY (source_id, card_id, category, board)';"));
        Assert.Equal(1L, await ScalarAsync(connectionString, "SELECT COUNT(1) FROM pg_constraint WHERE conname = 'ux_totals_grain' AND pg_get_constraintdef(oid) = 'PRIMARY KEY (source_id, card_id, board)';"));
        Assert.Equal(0L, await ScalarAsync(connectionString, "SELECT COUNT(1) FROM pg_indexes WHERE indexname IN ('card_category_observations_pkey', 'card_deck_totals_pkey');"));
        Assert.Equal(1L, await ScalarAsync(connectionString, "SELECT COUNT(1) FROM pg_indexes WHERE tablename = 'card_category_observations' AND indexdef LIKE '%(source_id, card_id, category, board)%';"));
        Assert.Equal(1L, await ScalarAsync(connectionString, "SELECT COUNT(1) FROM pg_indexes WHERE tablename = 'card_deck_totals' AND indexdef LIKE '%(source_id, card_id, board)%';"));
    }

    private static async Task<long> ScalarAsync(string connectionString, string sql)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        return Convert.ToInt64(await command.ExecuteScalarAsync());
    }

    private static async Task<TemporaryDatabase> CreateDatabaseAsync(string adminConnectionString)
    {
        var name = $"df_compact_{Guid.NewGuid():N}";
        var quotedName = $"\"{name}\"";
        await using (var admin = new NpgsqlConnection(adminConnectionString))
        {
            await admin.OpenAsync();
            await using var command = new NpgsqlCommand($"CREATE DATABASE {quotedName};", admin);
            await command.ExecuteNonQueryAsync();
        }

        var target = new NpgsqlConnectionStringBuilder(adminConnectionString) { Database = name, Pooling = false };
        return new TemporaryDatabase(adminConnectionString, target.ConnectionString, quotedName);
    }

    private sealed class TemporaryDatabase : IAsyncDisposable
    {
        private readonly string _adminConnectionString;
        private readonly string _quotedName;

        public TemporaryDatabase(string adminConnectionString, string connectionString, string quotedName)
        {
            _adminConnectionString = adminConnectionString;
            ConnectionString = connectionString;
            _quotedName = quotedName;
        }

        public string ConnectionString { get; }

        public async ValueTask DisposeAsync()
        {
            NpgsqlConnection.ClearAllPools();
            await using var admin = new NpgsqlConnection(_adminConnectionString);
            await admin.OpenAsync();
            await using var command = new NpgsqlCommand($"DROP DATABASE IF EXISTS {_quotedName} WITH (FORCE);", admin);
            await command.ExecuteNonQueryAsync();
        }
    }
}
